// ─── Helpers ───────────────────────────────────────────────────────────────

function h1(text) {
  return new Paragraph({
    text,
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 480, after: 200 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "4f46e5", space: 6 } },
  });
}

function h2(text) {
  return new Paragraph({
    children: [new TextRun({ text, bold: true, size: 28, color: "1a1a2e" })],
    spacing: { before: 360, after: 120 },
  });
}

function h3(text) {
  return new Paragraph({
    children: [new TextRun({ text, bold: true, size: 24, color: "4f46e5" })],
    spacing: { before: 240, after: 80 },
  });
}

function para(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, size: 20, color: opts.color || "222222", italics: opts.italics, bold: opts.bold })],
    spacing: { after: opts.after ?? 100 },
    indent: opts.indent ? { left: convertInchesToTwip(0.35) } : undefined,
    alignment: opts.center ? AlignmentType.CENTER : undefined,
  });
}

function bullet(text, level = 0) {
  return new Paragraph({
    children: [new TextRun({ text, size: 20 })],
    bullet: { level },
    spacing: { after: 60 },
  });
}

function promptBox(lines) {
  const children = typeof lines === "string" ? [lines] : lines;
  const runs = [];
  children.forEach((line, i) => {
    runs.push(new TextRun({ text: line, font: "Courier New", size: 19, color: "0f172a" }));
    if (i < children.length - 1) runs.push(new TextRun({ text: "\n", font: "Courier New", size: 19 }));
  });
  return new Paragraph({
    children: runs,
    shading: { type: ShadingType.CLEAR, fill: "F0F4FF" },
    spacing: { after: 200 },
    border: {
      top:    { style: BorderStyle.SINGLE, size: 4, color: "4f46e5", space: 4 },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: "4f46e5", space: 4 },
      left:   { style: BorderStyle.SINGLE, size: 12, color: "4f46e5", space: 4 },
      right:  { style: BorderStyle.SINGLE, size: 4, color: "4f46e5", space: 4 },
    },
    indent: { left: convertInchesToTwip(0.15), right: convertInchesToTwip(0.15) },
  });
}

function sectionBanner(num, title, subtitle) {
  const children = [
    new TextRun({ text: `PHASE ${num}  `, bold: true, size: 34, color: "ffffff" }),
    new TextRun({ text: title, bold: true, size: 34, color: "ffffff" }),
  ];
  if (subtitle) {
    children.push(new TextRun({ text: `\n${subtitle}`, size: 20, color: "c7d2fe" }));
  }
  return new Paragraph({
    children,
    shading: { type: ShadingType.CLEAR, fill: "4f46e5" },
    spacing: { before: 480, after: 240 },
    indent: { left: convertInchesToTwip(0.2) },
  });
}

function divider() {
  return new Paragraph({
    border: { top: { style: BorderStyle.SINGLE, size: 4, color: "e2e8f0", space: 8 } },
    spacing: { before: 240, after: 240 },
  });
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

function labelPara(label, content) {
  return new Paragraph({
    children: [
      new TextRun({ text: `${label}: `, bold: true, size: 20, color: "4f46e5" }),
      new TextRun({ text: content, size: 20, color: "333333" }),
    ],
    spacing: { after: 80 },
    indent: { left: convertInchesToTwip(0.15) },
  });
}

function noteBox(text) {
  return new Paragraph({
    children: [
      new TextRun({ text: "NOTE  ", bold: true, size: 18, color: "92400e" }),
      new TextRun({ text, size: 18, color: "451a03" }),
    ],
    shading: { type: ShadingType.CLEAR, fill: "FEF3C7" },
    spacing: { after: 160 },
    indent: { left: convertInchesToTwip(0.15), right: convertInchesToTwip(0.15) },
    border: { left: { style: BorderStyle.SINGLE, size: 12, color: "f59e0b", space: 4 } },
  });
}

